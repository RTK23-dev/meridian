import assert from "node:assert/strict";
import { createHash, randomUUID } from "node:crypto";
import test from "node:test";
import { getSql } from "../../db.ts";
import type { MultimodalPerceptionProvider, PerceptionMedia } from "../perception/types.ts";
import { PNG, studioTenant } from "../testing/durable-image-fixtures.ts";
import { checkVisualReadBytes, readVisualMedia, VISUAL_READ_MAX_BYTES } from "./vision.server.ts";

// The shared perception credential is set for this process only, as production resolves it: the deployment's shared default.
process.env.TOKEN_ENCRYPTION_KEY = process.env.TOKEN_ENCRYPTION_KEY || "test-master-key-0123456789abcdef-vision";
process.env.PERCEPTION_SHARED_DEFAULT = "gemini";
process.env.MERIDIAN_GEMINI_API_KEY = "test-shared-gemini-key-vision";

const sha256 = (bytes: Uint8Array) => createHash("sha256").update(bytes).digest("hex");
const JPEG = new Uint8Array([0xff, 0xd8, 0xff, 0xe0, 0x00, 0x10, 0x4a, 0x46, 0x49, 0x46, 0x00, 0x01]);
const WEBP = new Uint8Array(Buffer.from("RIFF\x10\x00\x00\x00WEBPVP8 ", "latin1"));

test("the visual read accepts PNG, JPEG and WebP by their magic bytes", () => {
  assert.deepEqual(checkVisualReadBytes(PNG, "still"), { ok: true, mimeType: "image/png" });
  assert.deepEqual(checkVisualReadBytes(JPEG, "still"), { ok: true, mimeType: "image/jpeg" });
  assert.deepEqual(checkVisualReadBytes(WEBP, "still"), { ok: true, mimeType: "image/webp" });
});

test("the visual read refuses garbage, an error page, an empty item, and any other image type by its bytes", () => {
  const garbage = checkVisualReadBytes(new TextEncoder().encode("this is not an image, only text a provider returned"), "still");
  assert.equal(garbage.ok, false, "text that is not a PNG, JPEG or WebP is refused");
  const page = checkVisualReadBytes(new TextEncoder().encode("<!doctype html><html><body>Rate limited</body></html>"), "still");
  assert.equal(page.ok, false, "an HTML error page is refused");
  assert.equal(checkVisualReadBytes(new Uint8Array(0), "still").ok, false, "an empty item is refused");
  // A PNG signature with a forged name is still judged by the bytes that follow the signature, not by the claim.
  const forged = new Uint8Array(PNG);
  forged[1] = 0x00;
  assert.equal(checkVisualReadBytes(forged, "still").ok, false, "a damaged PNG signature is not a PNG");
  const gif = checkVisualReadBytes(new TextEncoder().encode("GIF89a\x01\x00\x01\x00\x00\x00\x00;"), "still");
  assert.equal(gif.ok, false, "a GIF is a real image, but the visual read accepts only PNG, JPEG and WebP");
});

test("the visual read caps the size of one image at 10 MB, and refuses a larger one before anything is sent", () => {
  assert.equal(VISUAL_READ_MAX_BYTES, 10 * 1024 * 1024);
  const oversized = new Uint8Array(VISUAL_READ_MAX_BYTES + 1);
  oversized.set(PNG.slice(0, 8), 0);
  const check = checkVisualReadBytes(oversized, "still");
  assert.equal(check.ok, false);
  assert.match(!check.ok ? check.reason : "", /limit/);
  const atCap = new Uint8Array(VISUAL_READ_MAX_BYTES);
  atCap.set(PNG.slice(0, 8), 0);
  assert.equal(checkVisualReadBytes(atCap, "still").ok, true, "an image exactly at the cap is accepted");
});

test("the generated bytes reach the configured perception provider, and a refused item is never sent", async () => {
  const sql = await getSql();
  const tenant = await studioTenant(sql, "vision-bytes");
  const received: PerceptionMedia[][] = [];
  const provider: MultimodalPerceptionProvider = {
    id: "vision_stub",
    model: "vision-stub-1",
    promptVersion: "vision-stub.v1",
    health: async () => ({ id: "vision_stub", state: "HEALTHY", detail: "ready" }),
    perceive: async (input) => {
      received.push(input.media);
      return {
        status: "observed",
        providerId: "vision_stub",
        model: "vision-stub-1",
        promptVersion: "vision-stub.v1",
        observations: input.media.map((item) => ({
          mediaId: item.id, sha256: item.sha256, timestampMs: null, basis: "inferred" as const, productPresence: true,
        })),
        latencyMs: 1,
      };
    },
  };
  const base = { organizationId: tenant.organizationId, brandId: tenant.brandId, subjectType: "creative", subjectId: `creative-${randomUUID()}`, kind: "image" as const, provider };

  const sent = await readVisualMedia(sql, { ...base, media: [{ id: "still-generated", bytes: PNG, timestampMs: null, label: "Generated image" }] });
  assert.equal(sent.status, "observed", "a valid still is perceived");
  assert.equal(received.length, 1, "the provider is called once");
  const [item] = received[0]!;
  assert.ok(item && Buffer.from(item.bytes).equals(Buffer.from(PNG)), "the provider receives the generated bytes themselves");
  assert.equal(item.mimeType, "image/png");
  assert.equal(item.sha256, sha256(PNG), "the hash is taken from the bytes that were sent");

  const refused = await readVisualMedia(sql, { ...base, subjectId: `creative-${randomUUID()}`, media: [{ id: "still-bad", bytes: new TextEncoder().encode("<html>oops</html>"), timestampMs: null, label: "Generated image" }] });
  assert.equal(refused.status, "failed");
  assert.equal(refused.failureKind, "unsupported_media");
  assert.equal(refused.runId, "", "a refused read has no provider run");
  assert.equal(received.length, 1, "nothing was sent for the refused item");

  const unconfigured = await readVisualMedia(sql, { ...base, subjectId: `creative-${randomUUID()}`, provider: null, providerReason: "No perception provider is ready.", media: [{ id: "still-x", bytes: PNG, timestampMs: null, label: "Generated image" }] });
  assert.equal(unconfigured.status, "failed");
  assert.equal(unconfigured.failureKind, "not_configured");
  assert.equal(received.length, 1);
});
