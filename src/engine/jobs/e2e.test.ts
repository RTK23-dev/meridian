// One request, from intake to a take verdict, on PGlite with recorded provider answers (Video Engine Bible 19, E3 integration).
// The real pieces run: the orchestrator and its SQL, the dispatcher, the production handlers from runtime.ts, the Claude client
// with the role-call journal, the budget ledger, the kit store, the plan's own builder, and the asset router's stock path.
//
// Two stages are recorded stand-ins, and each says so in its gate: analyze_reference and voice (W6, not on this branch, with the
// Bible 8.1 edit grammar). Their outputs are the contract fixtures of the chain. The measurements the take gate needs (black
// frames, flicker, motion, the palette and the similarity scorer) have no media function or vendor yet, so the take gate has
// missing evidence and escalates, as Bible 12 requires. The tests assert that outcome; they do not pass a take that was not measured.
//
// The recorded plan answers name shot ids that are derived from the fixture request id, so every test uses that id, in its own
// database. No test calls a live API: the transport answers from the recorded responses and fails on any request it was not told to expect.

